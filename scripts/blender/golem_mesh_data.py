#!/usr/bin/env python3
"""Writes src/server/Models/GolemMeshData.luau from the Blender export.

Inputs, both in assets/models/golems/:
  golem_meshes.json  offsets and sizes, written by build_golems.py export_fbx()
  mesh_ids.json      {"<tier>/<Slot>_<Role>": <uploaded mesh asset id>}, filled
                     in after the FBX files are imported in Studio

A mesh with no id yet is left out, and a slot is only used once all of its
meshes have ids, so the game keeps its fallback art until the upload is done.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
FOLDER = ROOT / "assets" / "models" / "golems"
OUT = ROOT / "src" / "server" / "Models" / "GolemMeshData.luau"


def vec(values):
    return "Vector3.new(" + ", ".join(f"{v:g}" for v in values) + ")"


def main():
    meshes = json.loads((FOLDER / "golem_meshes.json").read_text())
    ids_path = FOLDER / "mesh_ids.json"
    ids = json.loads(ids_path.read_text()) if ids_path.exists() else {}
    lines = [
        "--!strict",
        "-- Generated by scripts/blender/golem_mesh_data.py from the Blender export",
        "-- (assets/models/golems). Do not edit by hand; rerun the script.",
        "-- tier -> slot -> role -> uploaded mesh id, bounding-box offset from the",
        "-- slot centre and size, in golem scale-1 studs.",
        "",
        "export type Mesh = { id: number, offset: Vector3, size: Vector3 }",
        "",
        "local data: { [string]: { [string]: { [string]: Mesh } } } = {",
    ]
    for tier in sorted(meshes):
        slots = []
        for slot in sorted(meshes[tier]):
            roles = meshes[tier][slot]
            if not all(ids.get(f"{tier}/{slot}_{role}") for role in roles):
                continue
            slots.append(f"\t\t{slot} = {{")
            for role in sorted(roles):
                m = roles[role]
                mesh_id = int(ids[f"{tier}/{slot}_{role}"])
                # One field per line, as StyLua formats it.
                slots += [
                    f"\t\t\t{role} = {{",
                    f"\t\t\t\tid = {mesh_id},",
                    f"\t\t\t\toffset = {vec(m['offset'])},",
                    f"\t\t\t\tsize = {vec(m['size'])},",
                    "\t\t\t},",
                ]
            slots.append("\t\t},")
        if slots:
            lines += [f"\t{tier} = {{", *slots, "\t},"]
    if lines[-1].endswith("= {"):
        lines[-1] += "}"
    else:
        lines.append("}")
    lines += ["", "return data", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
